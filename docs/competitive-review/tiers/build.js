// Builds the Free and paid board and RESEARCH.md from the data files beside it.
//   node docs/competitive-review/tiers/build.js [out.html]
// Without an argument the page is written to tier-board.html here; pass the
// scratchpad path the artifact was published from to republish the same URL.
const fs = require('fs');
const path = require('path');

const here = __dirname;
const { KINDS, SOURCES, FAMILIES, EVALUATION } = require('./research.js');
const built = JSON.parse(fs.readFileSync(path.join(here, 'functions-built.json'), 'utf8'));
const planned = require('./planned.js');

const TABS = built.TABS.filter(([k]) => k !== 'across');
TABS.push(['interests', 'Interests'], ['across', 'Across the app'], ['companions', 'Companions']);
const acrossName = (built.TABS.find(([k]) => k === 'across') || [])[1];
if (acrossName) TABS.find(([k]) => k === 'across')[1] = acrossName;

const F = [...built.F, ...planned];

// Checks: unique ids, every function in a family, every family and source resolves.
const famIds = new Set(FAMILIES.map(f => f.id));
const tabIds = new Set(TABS.map(([k]) => k));
const seen = new Set();
const problems = [];
F.forEach(d => {
  if (seen.has(d.id)) problems.push('duplicate id ' + d.id);
  seen.add(d.id);
  if (!famIds.has(d.fam)) problems.push(d.id + ' has unknown family ' + d.fam);
  if (!tabIds.has(d.t)) problems.push(d.id + ' has unknown tab ' + d.t);
  if (d.s && d.st) problems.push(d.id + ' is safety but not built');
});
FAMILIES.forEach(f => {
  (f.srcs || []).forEach(k => { if (!SOURCES[k]) problems.push(f.id + ' cites unknown source ' + k); });
  f.kinds.forEach(k => { if (!KINDS[k]) problems.push(f.id + ' has unknown kind ' + k); });
  if (!F.some(d => d.fam === f.id)) problems.push('family ' + f.id + ' has no functions');
});
EVALUATION.forEach(e => (e.fams || []).forEach(k => { if (!famIds.has(k)) problems.push('evaluation cites unknown family ' + k); }));
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

// The board.
const template = fs.readFileSync(path.join(here, 'board-template.html'), 'utf8');
if (!template.includes('/*DATA*/null')) throw new Error('template has no /*DATA*/null placeholder');
const data = JSON.stringify({ TABS, F, FAMILIES, KINDS, SOURCES, EVALUATION }).replace(/</g, '\\u003c');
const out = process.argv[2] || path.join(here, 'tier-board.html');
fs.writeFileSync(out, template.replace('/*DATA*/null', () => data));

// RESEARCH.md
const cell = s => String(s || '').replace(/\|/g, '/').replace(/\n/g, ' ');
const tabName = Object.fromEntries(TABS);
const ST = { planned: 'planned', asked: 'waiting on a decision', companion: 'companion tier' };
const md = [];
md.push('# Free and paid: why other apps give it away, and what Inside Story does');
md.push('');
md.push('Generated by `node docs/competitive-review/tiers/build.js` from `research.js`, `functions-built.json` and `planned.js`. Edit those, never this file.');
md.push('');
md.push(`${F.length} functions on the board: ${built.F.length} built, ${planned.filter(d => d.st === 'planned').length} planned, ${planned.filter(d => d.st === 'asked').length} waiting on a decision, ${planned.filter(d => d.st === 'companion').length} companion tiers. ${FAMILIES.length} families.`);
md.push('');
md.push('## How Inside Story can make more of itself pay caliber');
md.push('');
EVALUATION.forEach((e, i) => {
  md.push(`${i + 1}. **${e.h}.** ${e.b}` + (e.fams && e.fams.length ? ' Rests on: ' + e.fams.map(k => `[${FAMILIES.find(f => f.id === k).name}](#fam-${k})`).join(', ') + '.' : ''));
});
md.push('');
md.push('## Why things are free or paid: the kinds');
md.push('');
Object.values(KINDS).forEach(k => md.push(`- **${k.name}.** ${k.text}`));
md.push('');
md.push('## The families');
FAMILIES.forEach(f => {
  md.push('');
  md.push(`<a id="fam-${f.id}"></a>`);
  md.push(`### ${f.name}`);
  md.push('');
  md.push('Kinds: ' + f.kinds.map(k => KINDS[k].name).join(', ') + '.');
  md.push('');
  md.push('**Why it is free or paid elsewhere.** ' + f.whyFree);
  md.push('');
  md.push('| App | Price | Free | Paid | Source |');
  md.push('|---|---|---|---|---|');
  f.comps.forEach(c => md.push(`| ${cell(c.app)} | ${cell(c.price)} | ${cell(c.free)} | ${cell(c.paid)} | ${[...c.src.map(u => `<${u}>`), c.r].filter(Boolean).join(' ')} |`));
  if (f.srcs && f.srcs.length) {
    md.push('');
    f.srcs.forEach(k => md.push(`- ${SOURCES[k].finding} [${SOURCES[k].t}](${SOURCES[k].url})`));
  }
  md.push('');
  md.push('**What Inside Story does.** ' + f.ours);
  md.push('');
  md.push('**How it reaches pay caliber.** ' + f.lift);
  md.push('');
  md.push('On the board: ' + F.filter(d => d.fam === f.id).map(d => `${d.n} (${tabName[d.t]}${d.st ? ', ' + ST[d.st] : ''})`).join('; ') + '.');
});
md.push('');
md.push('## General evidence');
md.push('');
Object.values(SOURCES).forEach(s => md.push(`- [${s.t}](${s.url}). ${s.finding}`));
md.push('');
fs.writeFileSync(path.join(here, 'RESEARCH.md'), md.join('\n'));

console.log(`wrote ${out} (${fs.statSync(out).size} bytes) and RESEARCH.md; ${F.length} functions, ${FAMILIES.length} families`);
