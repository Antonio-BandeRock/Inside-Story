export function cropPubmedUrl(guide: CropGuide): string {
  const species = guide.latin.split(',')[0].replace(/\(.*?\)/g, '').replace(/\bspp\.|\bsubsp\..*$|\bagg\./g, '').trim();
  return pubmedSearchUrl(`${species} nutrient deficiency`);
}

// Every source a guide shows: its advisory services, then PubMed.
export function cropSources(guide: CropGuide): GuideSource[] {
  return [...guide.sources, { label: 'PubMed: the research on this crop', url: cropPubmedUrl(guide) }];
}

function normalize(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9 ]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// Food names that begin with a crop's word but are not the crop.
const NOT_A_CROP = ['pepper black', 'black pepper', 'pepper white', 'white pepper', 'corn flakes', 'cornflakes', 'corn starch', 'cornstarch', 'orange juice drink', 'lime juice cordial'];

type AliasEntry = { alias: string; guide: CropGuide };
const ALIAS_INDEX: AliasEntry[] = CROP_GUIDES.flatMap((guide) => guide.aliases.map((alias) => ({ alias: normalize(alias), guide }))).sort(
  (a, b) => b.alias.length - a.alias.length,
);

// The guide for a saved food name, or null. The name has to begin with
// the alias as whole words, so "Mangosteen" is not a mango and
// "Peppermint" is mint only because mint lists it.
export function findCropGuide(foodName: string | null | undefined): CropGuide | null {
  if (!foodName) return null;
  const name = normalize(foodName);
  if (!name || NOT_A_CROP.some((phrase) => name.startsWith(phrase))) return null;
  for (const { alias, guide } of ALIAS_INDEX) {
    if (name === alias || name.startsWith(`${alias} `)) return guide;
  }
  return null;
}

export function findCropGuideByKey(key: string | null | undefined): CropGuide | null {
  if (!key) return null;
  return CROP_GUIDES.find((guide) => guide.key === key) ?? null;
}

export function searchCropGuides(query: string): CropGuide[] {
  const q = normalize(query);
  if (!q) return CROP_GUIDES;
  return CROP_GUIDES.filter((guide) => {
    const haystack = normalize([guide.name, guide.latin, guide.family, ...guide.aliases].join(' '));
    return q.split(' ').every((word) => haystack.includes(word));
  });
}

export function formatPh([low, high]: [number, number]): string {
  return `pH ${low.toFixed(1)} to ${high.toFixed(1)}`;
}

