// How to grow each crop: the soil it wants, how to sow and space it, when
// it is ready, and the shortages and disorders it is known for, with every
// guide pointing out to the advisory service it stands on and to PubMed.
//
// 2026-09-26, direct request: "In the Garden tab, there needs to be
// information about how to grow each thing, what type of soil it likes,
// what deficiencies of nutrients look like and how to fix it based on
// real world gardening advice they can be pointed to, like PubMed,
// outside of the device."
//
// Where the words come from. The how-to is the kind of guidance the Royal
// Horticultural Society and the University of Florida's IFAS extension
// service publish, the first for temperate gardens and the second for
// warm and tropical ones, since the app is not only for cold climates.
// Each guide links to that service's page for the crop, every link
// checked by scripts/test_crop_guides.js. The figures (pH, spacing, days)
// are the ranges those services commonly give; the linked page carries
// the detail for a particular climate, and the in-app help says so.
// PubMed is linked as a search on the crop's Latin name, which shows the
// research for anyone who wants depth and always resolves.
//
// A planting in Garden > Plots & Plantings is matched to its guide by the
// food name it was saved under (findCropGuide), so "Tomatoes, cherry
// tomatoes, fruit" and "Tomato" both open the tomato guide. Longest alias
// wins, so "Squash, zucchini" is a courgette before it is a squash.
//
// Pure data and two lookups, no React, checked without a phone.

import { pubmedSearchUrl, type GuideSource, type PlantNutrientKey } from './plantNutrients';

export type CropGroup = 'vegetables' | 'herbs' | 'fruit' | 'warm';

export const CROP_GROUP_LABELS: Record<CropGroup, string> = {
  vegetables: 'Vegetables',
  herbs: 'Herbs',
  fruit: 'Fruit',
  warm: 'Warm Climate and Tropical',
};

export type CropWatchFor = {
  // The nutrient behind it, when there is one, so the row can open that
  // nutrient's whole account. A disorder with no nutrient (clubroot,
  // bolting) leaves it out.
  nutrient?: PlantNutrientKey;
  label: string;
  note: string;
};

export type CropGuide = {
  key: string;
  name: string;
  // Lower-case words a saved food name starts with. Punctuation is ignored.
  aliases: string[];
  latin: string;
  family: string;
  group: CropGroup;
  season: 'cool' | 'warm' | 'perennial';
  sun: string;
  soil: string;
  ph: [number, number];
  feeding: 'light' | 'moderate' | 'heavy';
  sow: string;
  spacing: string;
  ready: string;
  water: string;
  grow: string;
  watchFor: CropWatchFor[];
  sources: GuideSource[];
};

const rhs = (kind: 'vegetables' | 'fruit' | 'herbs', slug: string, label: string): GuideSource => ({
  label: `RHS: ${label}`,
  url: `https://www.rhs.org.uk/${kind}/${slug}/grow-your-own`,
});
